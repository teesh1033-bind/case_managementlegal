function legalpro_render_availability_date_picker_script(): void
{
    static $rendered = false;
    if ($rendered) {
        return;
    }
    $rendered = true;

    echo '<script>'
        . '(function(){'
        . 'function formatFlatpickrDate(date){'
        . 'if(!(date instanceof Date)||isNaN(date.getTime())){return "";}'
        . 'var y=date.getFullYear();'
        . 'var m=String(date.getMonth()+1).padStart(2,"0");'
        . 'var d=String(date.getDate()).padStart(2,"0");'
        . 'return y+"-"+m+"-"+d;'
        . '}'
        . 'function getPickerAnchor(instance){'
        . 'if(!instance){return null;}'
        . 'return instance.altInput||instance._input||instance.input||null;'
        . '}'
        . 'function alignCalendarBelowInput(instance){'
        . 'if(!instance||!instance.calendarContainer){return;}'
        . 'var anchor=getPickerAnchor(instance);'
        . 'if(!anchor){return;}'
        . 'var cal=instance.calendarContainer;'
        . 'var rect=anchor.getBoundingClientRect();'
        . 'var calWidth=cal.offsetWidth||268;'
        . 'var left=Math.round(rect.left);'
        . 'var top=Math.round(rect.bottom+4);'
        . 'if(left+calWidth>window.innerWidth-8){left=Math.max(8,window.innerWidth-calWidth-8);}'
        . 'if(top+cal.offsetHeight>window.innerHeight-8){top=Math.max(8,Math.round(rect.top-cal.offsetHeight-4));}'
        . 'cal.classList.add("legalpro-calendar-below");'
        . 'cal.style.setProperty("position","fixed","important");'
        . 'cal.style.setProperty("left",left+"px","important");'
        . 'cal.style.setProperty("top",top+"px","important");'
        . 'cal.style.setProperty("right","auto","important");'
        . 'cal.style.setProperty("transform","none","important");'
        . 'cal.style.setProperty("margin","0","important");'
        . 'cal.style.zIndex="10050";'
        . '}'
        . 'function bindCalendarReposition(instance){'
        . 'if(!instance||instance._legalproRepositionBound){return;}'
        . 'instance._legalproReposition=function(){if(instance.isOpen){alignCalendarBelowInput(instance);}};'
        . 'window.addEventListener("scroll",instance._legalproReposition,true);'
        . 'window.addEventListener("resize",instance._legalproReposition);'
        . 'instance._legalproRepositionBound=true;'
        . '}'
        . 'function unbindCalendarReposition(instance){'
        . 'if(!instance||!instance._legalproRepositionBound){return;}'
        . 'window.removeEventListener("scroll",instance._legalproReposition,true);'
        . 'window.removeEventListener("resize",instance._legalproReposition);'
        . 'instance._legalproReposition=null;'
        . 'instance._legalproRepositionBound=false;'
        . '}'
        . 'window.LegalproAvailabilityDatePicker={'
        . 'instances:{},'
        . 'create:function(input,options){'
        . 'options=options||{};'
        . 'var el=typeof input==="string"?document.getElementById(input):input;'
        . 'if(!el||typeof flatpickr==="undefined"){return null;}'
        . 'var key=el.id||el.name||String(Math.random());'
        . 'if(this.instances[key]){unbindCalendarReposition(this.instances[key]);this.instances[key].destroy();delete this.instances[key];}'
        . 'var self=this;'
        . 'var wrap=el.closest(".ca-date-picker-wrap,.legalpro-date-picker-wrap")||el.parentElement;'
        . 'var usePositionBelow=options.positionBelow!==false;'
        . 'var fp=flatpickr(el,{'
        . 'minDate:options.minDate||"today",'
        . 'dateFormat:"Y-m-d",'
        . 'allowInput:false,'
        . 'static:false,'
        . 'disable:[function(date){return typeof options.isUnavailable==="function"?!!options.isUnavailable(date):false;}],'
        . 'onDayCreate:function(selectedDates,inputValue,instance,dayElem){'
        . 'if(typeof options.isUnavailable==="function"&&dayElem){'
        . 'var checkDate=(dayElem.dateObj instanceof Date&&!isNaN(dayElem.dateObj.getTime()))?dayElem.dateObj:null;'
        . 'if(checkDate&&options.isUnavailable(checkDate)){dayElem.classList.add("legalpro-day-unavailable");}'
        . 'else{dayElem.classList.remove("legalpro-day-unavailable");}'
        . '}'
        . 'if(typeof options.onDayCreate==="function"){options.onDayCreate(selectedDates,inputValue,instance,dayElem);}'
        . '},'
        . 'onReady:function(selectedDates,dateStr,instance){'
        . 'if(instance&&instance.calendarContainer){'
        . 'instance.calendarContainer.classList.toggle("legalpro-flatpickr-dark",document.body.classList.contains("legalpro-dark-mode"));'
        . '}'
        . 'if(typeof options.onReady==="function"){options.onReady(selectedDates,dateStr,instance);}'
        . '},'
        . 'onChange:function(selectedDates,dateStr){if(typeof options.onChange==="function"){options.onChange(selectedDates,dateStr);}},'
        . 'onOpen:function(selectedDates,dateStr,instance){'
        . 'if(instance&&instance.calendarContainer){'
        . 'instance.calendarContainer.classList.toggle("legalpro-flatpickr-dark",document.body.classList.contains("legalpro-dark-mode"));'
        . '}'
        . 'if(usePositionBelow&&instance){'
        . 'var alignNow=function(){alignCalendarBelowInput(instance);};'
        . 'requestAnimationFrame(function(){alignNow();requestAnimationFrame(alignNow);});'
        . 'bindCalendarReposition(instance);'
        . '}'
        . 'if(typeof options.onOpen==="function"){options.onOpen(selectedDates,dateStr,instance);}'
        . '},'
        . 'onClose:function(selectedDates,dateStr,instance){'
        . 'if(instance){unbindCalendarReposition(instance);}'
        . 'if(typeof options.onClose==="function"){options.onClose(selectedDates,dateStr,instance);}'
        . '},'
        . 'appendTo:options.appendTo||(usePositionBelow?document.body:wrap)||undefined,'
        . 'defaultDate:options.defaultDate||el.value||null'
        . '});'
        . 'this.instances[key]=fp;'
        . 'return fp;'
        . '},'
        . 'refresh:function(input,options){'
        . 'options=options||{};'
        . 'var el=typeof input==="string"?document.getElementById(input):input;'
        . 'if(!el){return;}'
        . 'var fp=this.instances[el.id||el.name];'
        . 'if(!fp){return;}'
        . 'if(typeof options.isUnavailable==="function"){'
        . 'fp.set("disable",[function(date){return !!options.isUnavailable(date);}]);'
        . '}'
        . 'fp.redraw();'
        . '},'
        . 'rebuild:function(input,options){'
        . 'this.destroy(input);'
        . 'return this.create(input,options||{});'
        . '},'
        . 'clearIfUnavailable:function(input,isUnavailableFn){'
        . 'var el=typeof input==="string"?document.getElementById(input):input;'
        . 'if(!el||typeof isUnavailableFn!=="function"||!el.value){return;}'
        . 'var parts=el.value.split("-");'
        . 'if(parts.length<3){return;}'
        . 'var dateObj=new Date(parseInt(parts[0],10),parseInt(parts[1],10)-1,parseInt(parts[2],10));'
        . 'if(isUnavailableFn(dateObj)){'
        . 'var fp=this.instances[el.id||el.name];'
        . 'if(fp){fp.clear();}else{el.value="";}'
        . '}'
        . '},'
        . 'destroy:function(input){'
        . 'var el=typeof input==="string"?document.getElementById(input):input;'
        . 'if(!el){return;}'
        . 'var key=el.id||el.name;'
        . 'if(this.instances[key]){unbindCalendarReposition(this.instances[key]);this.instances[key].destroy();delete this.instances[key];}'
        . '},'
        . 'formatDate:formatFlatpickrDate'
        . '};'
        . '})();'
        . '</script>';
}
